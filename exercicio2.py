n1 = int(input("Digite um número: "))
n2 = int(input("digite o outro número: "))

soma = n1 + n2
sub = n1 - n2
multi = n1 * n2
div = n1 / n2

print(f'A soma dos números é: {soma}')
print(f'A subtração dos números é: {sub}')
print(f'A multiplicação dos números é: {multi}')
print(f'A divisão dos números é: {div:.2f}')
